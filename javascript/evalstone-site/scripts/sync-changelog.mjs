// Regenerates content/docs/evalstone/changelog.mdx from the library's CHANGELOG.md
// (python/evalstone/CHANGELOG.md is the single source of truth; this page is a build
// artifact that is also committed so the docs tree is complete on a fresh checkout).
// Runs before `next build` / `next dev`; python/evalstone/tests/test_docs.py fails when
// the committed copy is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, '../../../python/evalstone/CHANGELOG.md');
const target = resolve(here, '../content/docs/evalstone/changelog.mdx');

const md = readFileSync(source, 'utf8');
const firstRelease = md.indexOf('\n## ');
if (firstRelease === -1) throw new Error(`${source}: no "## <version>" heading`);
const body = md.slice(firstRelease + 1).trimEnd();

const page = `---
title: Changelog
description: Every release of the evalstone library, newest first.
---

{/* GENERATED by scripts/sync-changelog.mjs from python/evalstone/CHANGELOG.md — edit that file. */}

Every release of the \`evalstone\` library ([PyPI](https://pypi.org/project/evalstone/)), newest
first; semantic versioning, tags \`lib-vX.Y.Z\` in the
[repository](https://github.com/marceloribeiro/evalstone/blob/main/python/evalstone/CHANGELOG.md).
Install or upgrade with \`pip install -U evalstone\`.

${body}
`;
writeFileSync(target, page);
console.log(`changelog.mdx ← CHANGELOG.md (${body.split('\n## ').length} releases)`);
